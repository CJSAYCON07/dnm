export function getPixelSprite(key: string): HTMLCanvasElement {
  const cached = SPRITE_CACHE.get(key);
  if (cached) return cached;
  const def = SPRITE_DEFS[key] ?? SPRITE_DEFS.item_sword;
  const canvas = buildPixelCanvas(def.grid, def.palette);
  SPRITE_CACHE.set(key, canvas);
  return canvas;
}

export function getSpriteDataUrl(key: string): string {
  if (typeof document === 'undefined') return '';
  return getPixelSprite(key).toDataURL();
}
