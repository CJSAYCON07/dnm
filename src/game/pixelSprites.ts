// Procedural 16x16 & 24x24 pixel-art sprite sheet cache rendered to offscreen canvases

type Palette = Record<string, string>;

const SPRITE_CACHE = new Map<string, HTMLCanvasElement>();

function buildPixelCanvas(grid: string[], palette: Palette): HTMLCanvasElement {
  const h = grid.length;
  const w = grid[0].length;
  const canvas = document.createElement('canvas');
  canvas.width = w;
  canvas.height = h;
  const ctx = canvas.getContext('2d')!;
  ctx.imageSmoothingEnabled = false;
  for (let y = 0; y < h; y++) {
    const row = grid[y];
    for (let x = 0; x < w; x++) {
      const ch = row[x];
      if (ch === '.' || !palette[ch]) continue;
      ctx.fillStyle = palette[ch];
      ctx.fillRect(x, y, 1, 1);
    }
  }
  return canvas;
}

